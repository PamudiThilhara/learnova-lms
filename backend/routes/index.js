import { Router } from 'express';
import multer from 'multer';
import { rateLimit } from 'express-rate-limit';
import * as auth from '../controllers/auth.js';
import * as courses from '../controllers/courses.js';
import * as learning from '../controllers/learning.js';
import * as admin from '../controllers/admin.js';
import { requireAuth, roles } from '../services/auth.js';
import { stateFor, publicUser } from '../services/state.js';

export function apiRouter(config) {
  const router = Router();
  const authLimit = rateLimit({ windowMs: 15 * 60000, limit: config.NODE_ENV === 'test' ? 500 : 30, standardHeaders: 'draft-8', legacyHeaders: false, message: { message: 'Too many attempts. Please try again later.' } });
  const contactLimit = rateLimit({ windowMs: 3600000, limit: config.NODE_ENV === 'test' ? 500 : 10, standardHeaders: 'draft-8', legacyHeaders: false, message: { message: 'Too many messages. Please try again later.' } });
  const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 10 * 1024 * 1024, files: 1, fields: 3, fieldSize: 60000 } });
  router.get('/state', async (req, res) => res.json(await stateFor(req.user)));
  router.post('/auth/register', authLimit, auth.register);
  router.post('/auth/login', authLimit, auth.login);
  router.post('/auth/logout', auth.logout);
  router.get('/auth/me', requireAuth, (req, res) => res.json({ user: publicUser(req.user) }));
  router.patch('/auth/me', requireAuth, auth.updateProfile);
  router.post('/auth/forgot-password', authLimit, auth.forgotPassword);
  router.post('/auth/reset-password', authLimit, auth.resetPassword);
  router.get('/courses', courses.list);
  router.get('/courses/:id', courses.get);
  router.post('/courses', roles('instructor', 'admin'), courses.create);
  router.put('/courses/:id', roles('instructor', 'admin'), courses.update);
  router.delete('/courses/:id', roles('instructor', 'admin'), courses.remove);
  router.post('/courses/:id/enrollments', roles('student'), learning.enroll);
  router.put('/courses/:id/lessons/:lessonId/completion', roles('student'), learning.complete);
  router.post('/courses/:id/quiz-attempts', roles('student'), learning.quiz);
  router.put('/courses/:id/submission', roles('student'), upload.single('file'), learning.submit);
  router.patch('/courses/:id/submissions/:userId/grade', roles('instructor', 'admin'), learning.gradeSubmission);
  router.get('/courses/:id/submissions/:userId/attachment', requireAuth, learning.attachment);
  router.get('/courses/:id/certificate', roles('student'), learning.certificate);
  router.patch('/admin/users/:id/status', roles('admin'), admin.userStatus);
  router.delete('/admin/users/:id', roles('admin'), admin.deleteUser);
  router.put('/admin/settings', roles('admin'), admin.saveSettings);
  router.post('/admin/sample-data', roles('admin'), admin.samples);
  router.get('/admin/contact-messages', roles('admin'), admin.contacts);
  router.post('/contact-messages', contactLimit, admin.saveContact);
  return router;
}
